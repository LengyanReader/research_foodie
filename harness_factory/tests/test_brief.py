"""Guards for the task brief (P32): a paste-ready draft that renders what the
rules can compute and hands R4/R5 to the human - never a licence to start."""

from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

from harness_factory import brief
from harness_factory.spec import TaskSpec


class BriefRenderTest(unittest.TestCase):
    def test_brief_carries_all_eight_sections(self):
        built = brief.build(TaskSpec(text="Write a literature review with citations over several weeks"))
        text = brief.render(built)
        for section in ("0. Goal", "1. Constraints", "2. Feature vector", "3. Plan",
                        "4. Tiers", "5. Workflow", "6. First actions", "7. Gates", "8. Confirm"):
            self.assertIn(section, text, f"section missing: {section}")

    def test_brief_is_a_draft_not_a_licence(self):
        built = brief.build(TaskSpec(text="Write a literature review with citations over several weeks"))
        text = brief.render(built)
        self.assertIn("草案", text)
        self.assertIn("M0.4", text)
        self.assertIn("Generated by harness-factory", text)

    def test_brief_offers_the_three_tiers_with_mechanical_deltas(self):
        built = brief.build(TaskSpec(text="Write a literature review with citations over several weeks"))
        text = brief.render(built)
        self.assertIn("MVP", text)
        self.assertIn("Elevated", text)
        self.assertIn("Exploratory", text)

    def test_plans_differ_between_task_shapes(self):
        solo = brief.build(TaskSpec(text="Add unit tests to the parser"))
        team = brief.build(TaskSpec(text="Multi-agent literature review with citations over several weeks"))
        self.assertIn("M8", ", ".join(team["modules"]))
        self.assertNotIn("M8", ", ".join(solo["modules"]))

    def test_json_mode_serializes(self):
        built = brief.build(TaskSpec(text="Add unit tests to the parser"))
        payload = json.loads(brief.to_json(built))
        self.assertEqual(payload["features"]["domain"], built["features"].domain)


class BriefWriteTest(unittest.TestCase):
    def test_write_brief_lands_a_file(self):
        tmp = Path(tempfile.mkdtemp())
        built = brief.build(TaskSpec(text="Add unit tests to the parser"))
        path = brief.write_brief(built, tmp / "sub" / "brief.md")
        self.assertTrue(path.exists())
        self.assertIn("Task brief", path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
