"""Task brief (P32): goal -> a paste-ready execution brief.

``harness brief --task "…"`` renders the requirement-refinement fields whose
values the rules can compute (R0 restate, R2 constraint tiers, R3's three
offerings with their mechanical deltas), the derived plan, the first-phase
actions and the gates into one bilingual brief. R4/R5 stay pending-human:
the brief is a **draft to confirm**, never a licence to start - the
refinement doc's WAIT rule (M0.4: the factory renders what the rules say,
it never invents task substance).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .classify import classify
from .derive import derive
from .registry import domains as _domains
from .spec import TaskSpec

_HORIZON_NEXT = {"one_shot": "session", "session": "multi_session", "multi_session": "long_running"}

_HORIZON_ZH = {
    "one_shot": "一次性",
    "session": "单会话",
    "multi_session": "多会话",
    "long_running": "长时程",
}


def _features_table(f: Any) -> str:
    rows = [
        ("horizon · 时间跨度", _HORIZON_ZH.get(f.horizon, f.horizon), "rules (keywords)"),
        ("verifiability · 可验证性", f.verifiability, "rules (keywords)"),
        ("stakes · 风险", f.stakes, "rules (keywords)"),
        ("grounding · 来源要求", f.grounding, "domain default + explicit cues"),
        ("artifact · 产物", f.artifact, "domain default + explicit cues"),
        ("tool_surface · 工具面", f.tool_surface, "rules (keywords)"),
        ("collaboration · 协作", f.collaboration, "rules (keywords)"),
        ("domain · 领域", f.domain, "signal scoring (best domain)"),
    ]
    return "\n".join(f"| {k} | {v} | {why} |" for k, v, why in rows)


def _tiers(plan: Any) -> list[dict[str, str]]:
    """R3's three offerings: MVP is the derived plan; the other two name only
    the mechanical deltas - choosing one is the human's job (R4)."""
    f = plan.features
    tiers = [{"name": "MVP · 最小可行", "delta": "the plan below as derived; no changes."}]
    if f.horizon in _HORIZON_NEXT:
        delta = f"horizon {f.horizon} -> {_HORIZON_NEXT[f.horizon]}"
    else:
        delta = "horizon already maximal"
    if f.grounding != "required":
        delta += "; grounding -> required"
    tiers.append({"name": "Elevated · 拔高", "delta": delta + " (mechanical deltas only)."})
    if plan.secondary_domains:
        others = ", ".join(s["domain"] for s in plan.secondary_domains)
        tiers.append(
            {
                "name": "Exploratory · 探索",
                "delta": f"cross-domain with the named intersections ({others}); the target must be human-specified.",
            }
        )
    else:
        tiers.append(
            {"name": "Exploratory · 探索", "delta": "no declared intersection fired; the direction is human-specified."}
        )
    return tiers


def build(task: TaskSpec) -> dict[str, Any]:
    plan = derive(task, classify(task))
    f = plan.features
    meta = _domains().get(f.domain, {})
    workflow = meta.get("workflow", []) or []
    first_step = workflow[0] if workflow else "Define the deliverable and its acceptance criteria (M0.3)"
    instrument = (
        "literature/claims: semantic-scholar / crossref / openalex (catalogued instruments)"
        if f.grounding == "required"
        else "no named instrument required by the feature vector (M3.10: name one when the claim class appears)"
    )
    return {
        "task": task.text,
        "domain": f.domain,
        "domain_title": meta.get("title_en", f.domain),
        "domain_zh": meta.get("name_zh", ""),
        "features": f,
        "features_table": _features_table(f),
        "modules": [m.module_id for m in plan.enabled_modules()],
        "capabilities": plan.capabilities,
        "secondary_domains": plan.secondary_domains,
        "workflow": workflow,
        "first_step": first_step,
        "instrument": instrument,
        "tiers": _tiers(plan),
        "created": plan.created,
    }


def render(brief: dict[str, Any]) -> str:
    f = brief["features"]
    secondary = brief["secondary_domains"]
    sec_block = ""
    if secondary:
        rows = "\n".join(
            f"- **{s['domain']}**（score {s['score']}）{(' — ' + s['overlap']) if s.get('overlap') else ''}"
            for s in secondary
        )
        sec_block = f"\n**交叉域 · Secondary domains.**\n{rows}\n"
    workflow_list = "\n".join(f"{i + 1}. {step}" for i, step in enumerate(brief["workflow"])) or "_(no domain workflow)_"
    tiers_list = "\n".join(f"- **{t['name']}** — {t['delta']}" for t in brief["tiers"])
    modules = ", ".join(brief["modules"])
    caps = ", ".join(brief["capabilities"]) or "_(none)_"
    return f"""# Task brief · 任务简报（草案，待确认）

> Generated by harness-factory · {brief['created']} · domain {brief['domain']} ({brief['domain_title']} / {brief['domain_zh']})

## 0. Goal · 目标（R0 重述）

{brief['task']}

## 1. Constraints · 约束分级（R2）

- **hard · 硬**：M0 不变式（真·溯·验）＋ grounding={f.grounding}（来源要求是域默认或文本明示的契约）
- **soft · 软**：verifiability={f.verifiability}，stakes={f.stakes}——可由人改
- **assumed · 假设**：horizon={f.horizon}，tool_surface={f.tool_surface}，collaboration={f.collaboration}——规则按词表推得

## 2. Feature vector · 特征向量

| axis | value | why |
|---|---|---|
{brief['features_table']}

{sec_block}
## 3. Plan · 计划

- modules: {modules}
- capabilities: {caps}

## 4. Tiers · 三档（R3；选哪档由人定，R4）

{tiers_list}

## 5. Workflow · 工作流

{workflow_list}

## 6. First actions · 第一阶段行动

1. {brief['first_step']}
2. 建立 tasks/PLAN.md 骨架并写入验收标准（M0.3）
3. 声明证据仪器：{brief['instrument']}
4. 跑自检（`python .harness/check.py .` 或 `harness check --dir .`）

## 7. Gates · 门禁

- hard: 所有引用文件存在且无占位符；manifest 校验通过；grounding=required 时每条承重断言带来源+日期或标 `unverified`
- soft: 交付物与目标一致；人审通过

## 8. Confirm · 确认（R4–R5，开工前必答）

> 本简报是**草案**：确认目标表述、hard/soft 边界与所选档位后再开工（`reference/requirement-refinement.md`）。
> 工厂只渲染规则能算的部分，绝不替人写任务实质（M0.4）。
"""


def write_brief(brief: dict[str, Any], path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(brief), encoding="utf-8")
    return path


def to_json(brief: dict[str, Any]) -> str:
    payload = dict(brief)
    payload["features"] = {
        k: getattr(brief["features"], k) for k in ("horizon", "verifiability", "stakes", "grounding", "artifact", "tool_surface", "collaboration", "domain")
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)
