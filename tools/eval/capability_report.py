"""
Capability report — a scheduled snapshot of what each capability currently
scores on the relevant tools & benchmarks, plus the live base-model/tool
configuration that produced those numbers.

This is the "定时给出这个工具的各项功能在相关工具和 benchmark 上的表现"
mechanism (user 2026-09-20): it turns the scattered `_eval_out/` artifacts into
ONE dated, provenance-stamped view and keeps the reported configuration honest
(which model, which profile, which tool versions, measured `as of` when).

Sources it reads (all regenerated by other tools, never edited here):
  _eval_out/baselines.json      E-1 frozen capability baseline (mock/QA/judge/pools)
  _eval_out/variance_runs.json  latest judge re-runs (mean/sd per proxy topic)
  _eval_out/deps_ledger.json    E-4 tool/version ledger
  _eval_out/tickets.json        E-3 open debug board
  _eval_out/evolution_log.jsonl E-3 cadence history (via evolution.cadence_history)

Offline by default (reads cached artifacts, ~0 s, no LLM). `--live` first runs a
quick health cycle + dep verification so the snapshot reflects a fresh measure.

Usage:
    python -m tools.eval.capability_report                 # offline snapshot
    python -m tools.eval.capability_report --live          # re-measure first
    python -m tools.eval.capability_report --out <path>
"""
from __future__ import annotations

import argparse
import json
import statistics
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

REPO = Path(__file__).resolve().parents[2]
EVAL_OUT = REPO / "_eval_out"


# --------------------------------------------------------------------------- #
# safe readers (missing artifact -> None, never a crash)
# --------------------------------------------------------------------------- #
def _read_json(path: Path, default: Any = None) -> Any:
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError, OSError):
        return default


def _topic_variance(runs: Optional[List[Dict[str, Any]]]) -> Dict[str, Dict[str, Any]]:
    """Recompute per-topic mean/sd/n for the `total` axis from raw judge runs."""
    out: Dict[str, Dict[str, Any]] = {}
    if not runs:
        return out
    by_topic: Dict[str, List[float]] = {}
    for r in runs:
        tid, tot = r.get("topic_id"), r.get("total")
        if tid is None or not isinstance(tot, (int, float)):
            continue
        by_topic.setdefault(tid, []).append(float(tot))
    for tid, vals in by_topic.items():
        out[tid] = {
            "mean": round(statistics.mean(vals), 2),
            "sd": round(statistics.pstdev(vals), 2) if len(vals) > 1 else 0.0,
            "n": len(vals),
        }
    return out


# --------------------------------------------------------------------------- #
# report assembly (pure; testable with an injected eval dir)
# --------------------------------------------------------------------------- #
def build_report(eval_dir: Path = EVAL_OUT, live_note: str = "") -> str:
    now = datetime.now().isoformat(timespec="seconds")
    base = _read_json(eval_dir / "baselines.json", {}) or {}
    runs = _read_json(eval_dir / "variance_runs.json", []) or []
    deps = _read_json(eval_dir / "deps_ledger.json", {}) or {}
    board = _read_json(eval_dir / "tickets.json", {}) or {}

    # active profile / base-model configuration (message: keep config in docs)
    try:
        from tools.llm import profiles as _P
        prof = _P.load_profile()
        header = _P.profile_header(prof)
        options = list(_P.MODEL_OPTIONS)
    except Exception as e:  # pragma: no cover - defensive
        header = f"[profile unavailable: {type(e).__name__}]"
        options = []

    # self-evolution state
    open_t = board.get("tickets", []) if isinstance(board, dict) else []
    try:
        from tools.eval import evolution as _e
        fstat = _e.feedback_stats()
        hist = _e.cadence_history(limit=5)
    except Exception:  # pragma: no cover - defensive
        fstat, hist = {}, []

    L: List[str] = []
    L.append("# Capability & Benchmark Report — research_foodie")
    L.append("")
    L.append(f"> Generated `{now}` by `tools.eval.capability_report`. "
             f"Reads cached `_eval_out/` artifacts; every figure keeps its own "
             f"`as of` date below. {live_note}".strip())
    L.append("")

    # ---- 1. Configuration ------------------------------------------------- #
    L.append("## 1. Configuration (what ran)")
    L.append("")
    L.append(f"- **Active base-model profile:** `{header}`")
    if base.get("backend"):
        L.append(f"- **Baseline measured on:** `{base['backend'].get('llm','?')}`")
    if options:
        L.append("- **Selectable options** (`LLM_PROFILE`):")
        for o in options:
            L.append(f"  - `{o}`")
    tools = deps.get("tools", {}) if isinstance(deps, dict) else {}
    if tools:
        L.append(f"- **Tool ledger** (`as of {deps.get('as_of','?')}`):")
        L.append("")
        L.append("  | tool | version | status | severity |")
        L.append("  |---|---|---|---|")
        for name, info in tools.items():
            L.append(f"  | {name} | {info.get('version','—')} | "
                     f"{info.get('status','—')} | {info.get('severity','—')} |")
    L.append("")

    # ---- 2. Capability × benchmark --------------------------------------- #
    L.append("## 2. Capability × benchmark performance")
    L.append("")
    L.append(f"_Frozen baseline `as of {base.get('as_of','?')}`; judge is a "
             "non-deterministic free model — treat figures as directional (§4)._")
    L.append("")
    L.append("| capability | benchmark / test | measured | source |")
    L.append("|---|---|---|---|")
    mk = base.get("mock", {})
    _ma = mk.get("assertions", 0)
    _mf = mk.get("failures", 0)
    L.append(f"| Deterministic L6 gate + grounding | pipeline test (mock) | "
             f"**{_ma - _mf}/{_ma} PASS** "
             f"({_mf} failures) | `test_pipeline mock` |")
    qa = base.get("qa_panel", {})
    if qa:
        L.append(f"| Evidence-grounded QA (Track C) | QA panel | "
                 f"n={qa.get('n')} · correctness **{qa.get('correctness')}** · "
                 f"groundedness **{qa.get('groundedness')}** · {qa.get('pass')} | "
                 f"`bench_pilot_das.md` |")
    pools = base.get("pools", {})
    if pools:
        L.append(f"| Arbitrary-domain discovery | 30-topic pool battery | "
                 f"{pools.get('covered')}/{pools.get('total')} covered · "
                 f"{pools.get('empty')} empty | `pools_30_report.md` |")
    # judge trio: prefer recomputed-from-runs (freshest), fall back to baseline
    live_var = _topic_variance(runs)
    jv = base.get("judge_variance", {})
    if jv or live_var:
        L.append(f"| DAS-Bench 16-criterion judge | canonical trio (P-A/B/C) | see below | "
                 f"`variance_runs.json` / `baselines.json` |")
    L.append("")
    if jv or live_var:
        L.append("| topic | mean Total | sd | n |")
        L.append("|---|---|---|---|")
        for tid in sorted(set(jv) | set(live_var)):
            src = live_var.get(tid) or jv.get(tid) or {}
            L.append(f"| {tid} | {src.get('mean','—')} | {src.get('sd','—')} | "
                     f"{src.get('n','—')} |")
        L.append(f"_(raw judge runs in `variance_runs.json`: {len(runs)})_")
        L.append("")
    th = base.get("thresholds", {})
    if th:
        L.append(f"- **Regression thresholds (E-2):** FAIL ≥ {th.get('fail_sigma')}σ · "
                 f"WARN ≥ {th.get('warn_sigma')}σ — {th.get('warn_sigma_units','')}".rstrip(" —"))
        L.append("")

    # ---- 3. Self-evolution state ----------------------------------------- #
    L.append("## 3. Self-evolution state (WS-C)")
    L.append("")
    L.append(f"- **Open tickets:** {len(open_t)}"
             + (": " + ", ".join(t.get('component','?') for t in open_t) if open_t else " (board clear)"))
    if fstat:
        L.append(f"- **Feedback corpus:** {fstat.get('n')} rows · "
                 f"gold share {fstat.get('share')} (quota_ok={fstat.get('quota_ok')}, "
                 f"enforced={fstat.get('enforced')})")
    if hist:
        last = hist[-1]
        when = last.get("date") or last.get("ts", "?")
        levels: Dict[str, int] = {}
        for v in last.get("verdicts", []) or []:
            levels[v.get("level", "?")] = levels.get(v.get("level", "?"), 0) + 1
        lv = " · ".join(f"{k}={x}" for k, x in sorted(levels.items())) or "no verdicts"
        q = "quick" if last.get("quick") else "full"
        L.append(f"- **Last cadence** `{when}` ({q}): exit={last.get('exit_code','?')} · {lv}")
        if last.get("provenance"):
            L.append(f"  - provenance: `{last['provenance']}`")
        streak = [h.get("exit_code") for h in hist]
        L.append(f"- **Recent cadence exits:** {streak}")
    L.append("")

    # ---- 4. Honest boundaries -------------------------------------------- #
    L.append("## 4. Honest boundaries")
    L.append("")
    L.append("- Judge numbers come from a **non-deterministic free model** "
             "(±0.3–0.5); never head-to-head vs the published DAS table "
             "(needs a frozen ≥300B judge + DAS-2M pools + rendered pages).")
    L.append("- 8/30 evidence pools empty = arXiv relevance + parse caps, a "
             "**measured** property, not silent failure.")
    L.append("- This report **reads** artifacts only — it changes no code, no "
             "prompts, opens no PRs. Promotion stays human-gated.")
    L.append("")
    L.append("---")
    L.append(f"*Provenance: generated `{now}` · profile `{header}` · "
             "reproduce: `python -m tools.eval.capability_report`*")
    return "\n".join(L) + "\n"


def write_report(eval_dir: Path = EVAL_OUT, out: Optional[Path] = None,
                 live_note: str = "") -> Path:
    md = build_report(eval_dir=eval_dir, live_note=live_note)
    dest = out or (eval_dir / "capability_report.md")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(md, encoding="utf-8")
    return dest


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Scheduled capability + benchmark snapshot")
    ap.add_argument("--live", action="store_true",
                    help="run a quick health cycle + dep verify before snapshot")
    ap.add_argument("--out", default=None, help="output path (default _eval_out/capability_report.md)")
    ap.add_argument("--eval-dir", default=str(EVAL_OUT))
    args = ap.parse_args(argv)

    live_note = ""
    if args.live:
        try:
            from tools.eval.health_check import run_cycle
            from tools.eval import evolution as evo
            run_cycle(quick=True)
            evo.verify_deps()
            live_note = "(refreshed by a `--live` quick health+deps cycle)"
        except Exception as e:
            live_note = f"(--live refresh failed: {type(e).__name__}: using cached artifacts)"

    dest = write_report(Path(args.eval_dir), Path(args.out) if args.out else None, live_note)
    print(f"capability report -> {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
